def mapping():
    m = {}
    for cat, names in CATS.items():
        for n in names.replace("\n", "").split("|"):
            n = " ".join(n.split())
            if n:
                assert n not in m, f"duplicate {n}"
                m[n] = cat
    return m

if __name__ == "__main__":
    import sys
    m = mapping()
    q = lambda s: "'" + s.replace("'", "''") + "'"
    rows = ",\n".join(f"  ({q(n)}, {q(c)})" for n, c in sorted(m.items()))
    print("-- Категорії продуктів (відділи для закупівлі). Згенеровано scripts/product_categories.py")
    print("update public.products p set category = v.cat from (values\n" + rows + "\n) as v(name, cat) where p.name = v.name;")
