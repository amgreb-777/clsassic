export default function Help() {
  const [q, setQ] = useState('')
  const [open, setOpen] = useState<Record<string, boolean>>({ start: true })
  const refs = useRef<Record<string, HTMLElement | null>>({})
  const [hidden, setHidden] = useState<Set<string>>(new Set())

  // пошук по тексту розділів
  useEffect(() => {
    const n = q.trim().toLowerCase()
    if (!n) return setHidden(new Set())
    const h = new Set<string>()
    for (const s of SECTIONS) {
      const el = refs.current[s.id]
      const text = (s.title + ' ' + s.lead + ' ' + (el?.textContent ?? '')).toLowerCase()
      if (!text.includes(n)) h.add(s.id)
    }
    setHidden(h)
    setOpen(Object.fromEntries(SECTIONS.filter((s) => !h.has(s.id)).map((s) => [s.id, true])))
  }, [q])

  const go = (id: string) => {
    setOpen((o) => ({ ...o, [id]: true }))
    requestAnimationFrame(() => refs.current[id]?.scrollIntoView({ behavior: 'smooth', block: 'start' }))
  }
  const list = SECTIONS

  return (
    <div className="page help-page">
      <div className="page-head">
        <div className="grow">
          <div className="eyebrow">Довідка</div>
          <h1>Як користуватися платформою</h1>
          <p>Покрокові інструкції для всіх розділів: замовлення, меню, закупка, страви й техкарти, продукти, ціни, команда. Скористайтеся пошуком або змістом.</p>
        </div>
      </div>

      <div className="help-search">
        <SearchInput value={q} onChange={setQ} placeholder="Пошук у довідці: «PDF», «ручна ціна»…" />
      </div>

      {!q && (
        <nav className="help-toc" aria-label="Зміст довідки">
          {list.map((s, i) => (
            <button key={s.id} className="help-toc-item" onClick={() => go(s.id)}>
              <span className="n">{String(i + 1).padStart(2, '0')}</span>
              <span className="t"><b>{s.title}</b><small>{s.lead}</small></span>
              <Icon name={s.icon} size={20} />
            </button>
          ))}
        </nav>
      )}

      {q && hidden.size === list.length && <p className="muted help-none">Нічого не знайдено за «{q}». Спробуйте інше слово.</p>}

      <div className="help-sections">
        {list.map((s) => (
          <details
            key={s.id}
            ref={(el) => {
              refs.current[s.id] = el
            }}
            className="card help-sec"
            hidden={hidden.has(s.id)}
            open={!!open[s.id]}
            onToggle={(e) => {
              const v = (e.currentTarget as HTMLDetailsElement).open
              setOpen((o) => (o[s.id] === v ? o : { ...o, [s.id]: v }))
            }}
          >
            <summary>
              <span className="help-ico"><Icon name={s.icon} size={20} /></span>
              <span className="help-h">
                <b>{s.title}</b>
                <small>{s.lead}</small>
              </span>
              {s.admin && <span className="badge confirmed">адміністратор</span>}
            </summary>
            <div className="help-body">{s.body}</div>
          </details>
        ))}
      </div>

      <p className="help-foot muted small">Не знайшли відповіді? Зверніться до адміністратора команди.</p>
    </div>
  )
}
